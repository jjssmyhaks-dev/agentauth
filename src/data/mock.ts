function generateHash(data: string, prev: string): string {
  return "0x" + hashCode(data + prev);
}

let prevHash = "0x0000000000000000";

function entry(id: string, ts: string, actor: string, actorType: "agent" | "user" | "system", action: string, rt: string, resource: string, result: AuditEntry["result"], meta?: Record<string, unknown>): AuditEntry {
  const data = `${ts}:${actor}:${action}:${rt}:${resource}:${result}`;
  const hash = generateHash(data, prevHash);
  const entry: AuditEntry = { id, timestamp: ts, actor, actorType, action, resourceType: rt, resource, result, hash, previousHash: prevHash, metadata: meta };
  prevHash = hash;
  return entry;
}

